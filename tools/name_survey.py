def names():
    D = {}
    for jp, ko in TC.glossary():
        D[jp.replace('　', '')] = ko
        m = re.match(r'^(.+)の(.+)$', jp)
        if m and m.group(2) and '의 ' in ko: D[m.group(2)] = ko.split('의 ', 1)[1]   # 烈風の飛音 → 飛音
    import review_fix as RF
    for jp, _, _, ko in RF.TERMS:
        if re.search(r'[ァ-ヶ一-龥]', jp): D.setdefault(jp, ko)
    for jp, ko in EXTRA: D.setdefault(jp, ko)
    for k in SKIP: D.pop(k, None)
    return D


def main():
    sys.stdout.reconfigure(encoding='utf-8')
    D = names(); keys = sorted(D, key=len, reverse=True)
    out = []; cnt = collections.Counter(); seen = collections.Counter()
    for f in sorted(glob.glob(os.path.join(ROOT, 'my files', 'tsv', 'samsp_*.tsv'))):
        for l in open(f, encoding='utf8'):
            c = l.rstrip('\n').split('\t')
            if len(c) < 6 or c[0] == 'id': continue
            jp = re.sub(r'[\s　]', '', TOK.sub('', c[4])); ko = re.sub(r'\s', '', TOK.sub('', c[5]))
            used = jp
            for k in keys:
                if k not in used: continue
                used = used.replace(k, '\0')            # 긴 이름이 먼저 소비
                want = re.sub(r'\s', '', D[k]); seen[k] += 1
                if want in ko or (c[0], k) in OK: continue
                cnt[k] += 1; out.append((k, D[k], os.path.basename(f), c[0], c[1], c[2], c[3], c[4], c[5]))
    out.sort(key=lambda r: (-cnt[r[0]], r[0], r[3]))
    p = os.path.join(ROOT, 'work', 'review', 'name_survey.tsv')
    open(p, 'w', encoding='utf8').write('원문 이름\t바른 표기\t파일\tid\t종류\t위치\t예산\tJP\tKO\n' + ''.join('\t'.join(r) + '\n' for r in out))
    print('이름 %d개 · 출현 줄 %d · 표기 없음 %d줄 → %s' % (len(seen), sum(seen.values()), len(out), p))
    for k, n in cnt.most_common(): print('  %s → %s : %d / %d' % (k, D[k], n, seen[k]))


if __name__ == '__main__':
    main()
